import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const configUrl = new URL("wrangler.jsonc", root);
const workerUrl = new URL("src/worker.mjs", root);
const outputUrl = new URL("worker-env.d.ts", root);
const checkOnly = process.argv.includes("--check");

function fail(message) {
  throw new Error(`Worker environment contract: ${message}`);
}

const configSource = await readFile(configUrl, "utf8");
const workerSource = await readFile(workerUrl, "utf8");
const config = JSON.parse(configSource);

if (!config.compatibility_flags?.includes("nodejs_compat")) {
  fail('wrangler.jsonc must enable the "nodejs_compat" compatibility flag.');
}

const assetBinding = config.assets?.binding;
if (
  typeof assetBinding !== "string" ||
  !/^[A-Z][A-Z0-9_]*$/u.test(assetBinding)
) {
  fail("assets.binding must use an uppercase Worker binding identifier.");
}

const variableBindings = Object.keys(config.vars ?? {});
for (const binding of variableBindings) {
  if (!/^[A-Z][A-Z0-9_]*$/u.test(binding)) {
    fail(`vars.${binding} must use an uppercase Worker binding identifier.`);
  }
}

const configuredBindings = [assetBinding, ...variableBindings].sort();
const referencedBindings = [
  ...new Set(
    [...workerSource.matchAll(/\benv\.([A-Z][A-Z0-9_]*)/gu)].map(
      (match) => match[1],
    ),
  ),
].sort();

if (JSON.stringify(referencedBindings) !== JSON.stringify(configuredBindings)) {
  fail(
    `Worker references ${referencedBindings.join(", ") || "no bindings"}, ` +
      `but Wrangler config declares ${configuredBindings.join(", ")}.`,
  );
}

const configDigest = createHash("sha256")
  .update(JSON.stringify(config))
  .digest("hex")
  .slice(0, 16);
const variableFields = variableBindings
  .sort()
  .map((binding) => `  readonly ${binding}: string;`)
  .join("\n");
const generated = `// Generated by scripts/generate-worker-env.mjs from wrangler.jsonc.
// Configuration contract: sha256-${configDigest}
// Run "npm run generate:worker-env" after changing Worker bindings.

export interface BlogWorkerEnv {
  readonly ${assetBinding}: Fetcher;
${variableFields}
}
`;

if (checkOnly) {
  let current;
  try {
    current = await readFile(outputUrl, "utf8");
  } catch {
    fail('worker-env.d.ts is missing; run "npm run generate:worker-env".');
  }

  if (current !== generated) {
    fail('worker-env.d.ts is stale; run "npm run generate:worker-env".');
  }
} else {
  await writeFile(outputUrl, generated, "utf8");
}
